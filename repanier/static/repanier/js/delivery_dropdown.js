/*
 * Delivery point dropdown behaviour for the order screens.
 * Loaded once per page by cms_order_page.html; the dropdown widget is
 * rendered server side by CustomerInvoice.get_html_select_delivery_point
 * and its menu items come from delivery_select_ajax via HTMX.
 */

// Select a delivery point and update the order via delivery_ajax.
function selectDelivery(deliveryId, element) {
    const dropdown = element.closest('.dropdown');
    const deliveryAjaxUrl = dropdown.dataset.deliveryUrl;
    const permanence = dropdown.dataset.permanence;
    // On basket pages propagate the flag to delivery_ajax so the server
    // returns the basket-aware #span_btn_confirm_order update.
    const isBasket = dropdown.dataset.isBasket === 'yes';

    // Close the dropdown
    const bootstrapDropdown = bootstrap.Dropdown.getInstance(dropdown);
    if (bootstrapDropdown) {
        bootstrapDropdown.hide();
    }

    // deliveryAjaxUrl is generated by Django with the current language prefix.
    let url = deliveryAjaxUrl + '?delivery=' + deliveryId + '&permanence=' + permanence;
    if (isBasket) {
        url += '&is_basket=yes';
    }
    fetch(url, { cache: 'no-store' })
        .then(response => response.json())
        .then(result => {
            // result maps CSS selectors to HTML fragments to refresh:
            // the delivery point dropdown itself (new selected label and
            // shipping costs), the basket and the order confirmation box.
            for (const key in result) {
                if (result.hasOwnProperty(key)) {
                    const elements = document.querySelectorAll(key);
                    elements.forEach(el => {
                        el.innerHTML = result[key];
                        if (key === "#communicationModal") {
                            bootstrap.Modal.getOrCreateInstance(el).show();
                        }
                    });
                }
            }
        })
        .catch(error => console.error("delivery_ajax error:", error));
}
