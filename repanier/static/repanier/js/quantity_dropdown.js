/*
 * Quantity dropdown behaviour for the order screen.
 * Loaded once per page by cms_order_page.html; the dropdown widget itself is
 * rendered per offer item by the repanier_custom_quantity_dropdown tag.
 */

// Select a quantity and update the order via order_ajax.
function selectQuantity(offerItemId, quantity, element) {
    const dropdown = element.closest('.dropdown');
    const orderAjaxUrl = dropdown.dataset.orderUrl;
    // On basket pages (?is_basket=yes) propagate the flag to order_ajax so the
    // server returns the basket-aware #span_btn_confirm_order update.
    const isBasket = dropdown.dataset.isBasket === 'yes';

    // Close the dropdown
    const bootstrapDropdown = bootstrap.Dropdown.getInstance(dropdown);
    if (bootstrapDropdown) {
        bootstrapDropdown.hide();
    }

    // Update the displayed quantity
    const display = dropdown.querySelector('.quantity-display');
    display.textContent = quantity;

    // Keep the hidden select in sync for compatibility
    const hiddenSelect = document.getElementById('offer_item' + offerItemId);
    if (hiddenSelect) {
        hiddenSelect.value = quantity;
    }

    // orderAjaxUrl is generated by Django with the current language prefix.
    let url = orderAjaxUrl + '?offer_item=' + offerItemId + '&value=' + quantity;
    if (isBasket) {
        url += '&is_basket=yes';
    }
    fetch(url, { cache: 'no-store' })
        .then(response => response.json())
        .then(result => {
            // result maps CSS selectors to HTML fragments to refresh
            for (const key in result) {
                if (result.hasOwnProperty(key)) {
                    const elements = document.querySelectorAll(key);
                    elements.forEach(el => {
                        el.innerHTML = result[key];
                        if (key === "#communicationModal") {
                            bootstrap.Modal.getOrCreateInstance(el).show();
                        }
                    });
                }
            }
        })
        .catch(error => console.error("order_ajax error:", error));
}

// Open the "Other quantity" modal for the product of the clicked option.
function showOtherQtyModal(offerItemId, element) {
    // Close the dropdown
    const dropdown = element.closest('.dropdown');
    const bootstrapDropdown = bootstrap.Dropdown.getInstance(dropdown);
    if (bootstrapDropdown) {
        bootstrapDropdown.hide();
    }

    const productName = element.getAttribute('data-product-name') || '';

    const labelEl = document.getElementById('otherQtyModalLabel');
    if (labelEl) {
        labelEl.textContent = productName;
    }

    const otherQtyModalEl = document.getElementById('otherQtyModal');
    if (otherQtyModalEl) {
        const modal = bootstrap.Modal.getOrCreateInstance(otherQtyModalEl);
        modal.show();
    }
}
